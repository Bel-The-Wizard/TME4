"""The objects the harvest produces.

One harvested problem is the record

    𝒫ₙ = ( 𝒳ₙ, 𝒴ₙ, μₙ, ℰₙ, f* )        (docs/PROBLEM_HARVEST.md §1)

    𝒳ₙ  the inputs (graphs, covariance matrices, Hamiltonians, CNF formulas) on n sites
    𝒴ₙ  the outputs: here always {-1, +1}
    μₙ  the data distribution: here, the actual samples and their fixed TRAIN / TEST split
    ℰₙ  the equation every input determines (heat, Ornstein-Uhlenbeck, Schrödinger)
    f*  the target: the labels, and the rule that produced them

In code this is `HarvestedProblem`. Everything else in this file is a part of it.

The four problem types (docs/SUBFAMILIES.md §1, point 4) are named by the operator the
problem becomes after encoding, not by the domain it comes from:

    GRAPH       Laplacian of a graph (molecules, connectomes, program graphs, and 2-local Ising problems)
    COVARIANCE  precision matrix = inverse covariance (EEG, sensor time series, fMRI)
    DIAGONAL    Hamiltonian made only of Z terms with 3 or more qubits per term (SAT)
    QUANTUM     Hamiltonian with non-commuting terms (quantum spin chains, quantum chemistry)
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Literal, Optional

import numpy as np

ProblemType = Literal["GRAPH", "COVARIANCE", "DIAGONAL", "QUANTUM"]

Origin = Literal["REAL", "REAL_INPUT_COMPUTED_LABEL", "SYNTHETIC"]
"""Where a problem's inputs and labels come from (principle P5 of docs/HARVEST_SCALE.md):
REAL = real inputs and real labels; REAL_INPUT_COMPUTED_LABEL = real inputs, label computed
by us (e.g. 'is this molecule's skeleton bipartite?'); SYNTHETIC = both generated by us."""


@dataclass
class Instance:
    """One sample of a problem: an input x and its label y.

    x     the raw input, in the format of its problem type:
            GRAPH       {"n": int, "edges": [(i, j), ...], "node_types": [int, ...] or None}
            COVARIANCE  numpy array of shape (channels, time): one recorded trial
            DIAGONAL    {"n": int, "clauses": [(lit, lit, lit), ...]}   (DIMACS literals: +j / -j, j from 1)
            QUANTUM     {"n": int, "pauli": {"XXII": 1.0, ...}, "state": vector, "energy": float, "params": {...}}
    y     the label, +1 or -1
    unit  the name of the 'original' this sample comes from. Samples with the same unit always
          land on the same side of the TRAIN / TEST split (principle P4): e.g. several windows
          cut from one EEG trial, or the two members of a SAT/UNSAT pair.
    info  anything else worth keeping (parameter value, subject number, ...). Never used by
          the pipeline's decisions.
    """
    x: Any
    y: int
    unit: str
    info: dict = field(default_factory=dict)


@dataclass
class Operator:
    """The operator M(x) of one input: the object the input's equation is written with.

    kind     LAPLACIAN (graphs), PRECISION (covariance), HAMILTONIAN (quantum),
             CLAUSE_PENALTY (SAT: counts violated clauses)
    n        number of sites
    matrix   for LAPLACIAN and PRECISION: the n x n matrix M
    pauli    for HAMILTONIAN and CLAUSE_PENALTY: M as a Pauli sum {"ZZIZ": coefficient, ...}
    factors  how M was built, kept so it can be inspected. For graphs and covariance this is
             the discrete-form factorisation M = Bᵀ W B + V (docs/HARVEST_SCALE.md §3.2):
             B = oriented incidence matrix (edges x sites), w = edge weights (the diagonal of W),
             V = diagonal 'potential'. For Hamiltonians: which terms are the interaction (the dial).
    """
    kind: Literal["LAPLACIAN", "PRECISION", "HAMILTONIAN", "CLAUSE_PENALTY"]
    n: int
    matrix: Optional[np.ndarray] = None
    pauli: Optional[dict] = None
    factors: dict = field(default_factory=dict)


@dataclass
class CheckResult:
    """The outcome of an equation check on one input.

    method    which test was run (a short name, stored in the database)
    residual  how far from perfect: 0 is perfect; the meaning depends on the method
    passed    whether the residual is below the method's tolerance

    A failed check never removes or edits the sample (working rule: failures are recorded,
    never fixed by hand). It is counted in Equation.n_failed.
    """
    method: str
    residual: float
    passed: bool


@dataclass
class Equation:
    """ℰₙ: the differential equation every input of the problem determines.

    Mirrors the `equation` table of docs/DATA_STRUCTURE.md §4.2b.

    form           HEAT (dx/dt = -M x), ORNSTEIN_UHLENBECK (dx = -M x dt + noise),
                   SCHRODINGER (dψ/dt = -i M ψ)
    operator_kind  the Operator.kind used
    storage        SPARSE_MATRIX (an n x n matrix) or PAULI_SUM
    parameters     the fixed numbers of the equation (e.g. {"J": 1}); per-instance values
                   live in Instance.info
    nonlinearity   the part of the equation that is not linear / not free-fermion:
                   {"kind": "NONE" | "INTERACTION" | "K_LOCAL", "term": str, "strength": ...}.
                   This is the simulability dial (docs/DE_BRIDGE.md §4).
    check_method, check_max_residual, n_failed
                   filled in by the pipeline after checking every instance
    """
    form: Literal["HEAT", "ORNSTEIN_UHLENBECK", "SCHRODINGER"]
    operator_kind: str
    storage: Literal["SPARSE_MATRIX", "PAULI_SUM"]
    parameters: dict = field(default_factory=dict)
    nonlinearity: dict = field(default_factory=lambda: {"kind": "NONE"})
    check_method: str = ""
    check_max_residual: float = float("nan")
    n_failed: int = 0


@dataclass
class Provenance:
    """Where a problem comes from and how it was turned into our object.

    source, dataset, url, version, licence, citation   where the raw data came from
    raw_hash        sha256 of the downloaded raw file(s); "" for generated problems
    group_id        the independent source this problem belongs to (principle P2). Phase B is
                    validated by leaving one whole group out at a time.
    origin          REAL / REAL_INPUT_COMPUTED_LABEL / SYNTHETIC (principle P5)
    modelling_map   how the domain problem was turned into our object, with its parameters
                    (e.g. {"map": "EEG trial -> channel covariance", "channels": [...], "band": [8, 30]})
    """
    source: str
    dataset: str
    group_id: str
    origin: Origin
    url: str = ""
    version: str = ""
    licence: str = ""
    citation: str = ""
    raw_hash: str = ""
    modelling_map: dict = field(default_factory=dict)


@dataclass
class TaskOperator:
    """M̄: the single operator of the whole task, built from the TRAIN instances only.

    The instance operators M(x) feed the *encoding*; M̄ feeds the circuit's *trainable
    generators* (decision R4, docs/DE_BRIDGE.md §5).

    matrix / pauli  M̄ itself (same storage as the instance operators)
    support         which entries are 'present' (the locality): a list of site pairs (i, j) for
                    matrices, a list of Pauli strings for Pauli sums
    rule            a sentence saying how M̄ was built (stored, so the choice is visible)
    """
    kind: str
    matrix: Optional[np.ndarray] = None
    pauli: Optional[dict] = None
    support: list = field(default_factory=list)
    rule: str = ""


@dataclass
class HarvestedProblem:
    """One problem 𝒫ₙ, ready to be stored.

    task_id        unique name: "<source>:<dataset>:n=<n>:<label rule>"
    problem_type   GRAPH / COVARIANCE / DIAGONAL / QUANTUM
    n              number of sites (= qubits)
    instances      the samples (𝒳ₙ and 𝒴ₙ together)
    split          one entry per instance: "TRAIN" or "TEST" (μₙ realised)
    operators      M(x) for every instance, same order as `instances`
    checks         the equation check of every instance, same order
    equation       ℰₙ
    task_operator  M̄ (from TRAIN only)
    label_rule     f*, as a sentence: "as given by the source", "satisfiable (brute force)", ...
    provenance     where it comes from
    n_distinct     number of different inputs (screening rule S6)
    conflict_rate  fraction of samples whose input also appears with the other label (rule S7)
    balance_rule   what the class balancing did ("unchanged" or "downsampled ... ")
    """
    task_id: str
    problem_type: ProblemType
    n: int
    instances: list
    split: list
    operators: list
    checks: list
    equation: Equation
    task_operator: TaskOperator
    label_rule: str
    provenance: Provenance
    n_distinct: int
    conflict_rate: float
    balance_rule: str = "unchanged"

    @property
    def n_samples(self) -> int:
        """How many samples the problem has."""
        return len(self.instances)

    @property
    def class_balance(self) -> float:
        """Fraction of samples labelled +1."""
        return sum(1 for inst in self.instances if inst.y == 1) / max(1, len(self.instances))


@dataclass
class Rejection:
    """Why a candidate problem was not kept. Every rejection is written to the harvest log,
    so the funnel (listed -> screened -> converted -> checked -> kept) is itself a result."""
    stage: str
    reason: str
    n_samples: int = 0
